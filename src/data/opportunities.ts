export function getOpportunity(slug: string): Opportunity | undefined {
  return OPPORTUNITIES.find((o) => o.slug === slug);
}

export function relatedOpportunities(opp: Opportunity, limit = 3): Opportunity[] {
  const scored = OPPORTUNITIES.filter((o) => o.id !== opp.id).map((o) => {
    let score = 0;
    if (o.types.some((t) => opp.types.includes(t))) score += 2;
    if (o.sectors.some((s) => opp.sectors.includes(s))) score += 1;
    if (o.region === opp.region) score += 1;
    return { o, score };
  });
  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score || (a.o.deadline ?? '9999').localeCompare(b.o.deadline ?? '9999'))
    .slice(0, limit)
    .map((s) => s.o);
}
