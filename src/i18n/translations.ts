export function translate(key: string, lang: 'en' | 'zh', vars?: Record<string, string | number>): string {
  const entry = T[key];
  let s = entry ? entry[lang] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
